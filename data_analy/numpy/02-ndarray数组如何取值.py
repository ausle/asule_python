import numpy as np

# 1、一维数组
a = np.array([10, 20, 30, 40, 50])

# （1）基本索引：取一个元素
print(a[0])     # 10，第 1 个
print(a[2])     # 30，第 3 个
# 50，倒数第 1 个
print(a[-1])
# 获取全部数据
print(a[:])

# （2） 连续切片：a[起始位置:结束位置]
# [20 30 40]，不包含位置 4
print(a[1:4])

# [10 20 30]，从位置0开始，但不包含位置3
print(a[:3])
# [30 40 50]，从位置2开始，没指定结束位置，则直到数组结束。
print(a[2:])

# 3. 按步长切片：a[起始位置:结束位置:步长]
# 步长为2，隔一个取一个。最后的值为：[10 30 50]
print(a[::2])
# -1是倒序：[50 40 30 20 10]
print(a[::-1])

# 4. 使用 slice()
# 效果等同于 a[1:5:2]
rule0 = slice(1, 5, 2)
print(a[rule0])  # [20 40]

# 5. 布尔索引：只取满足条件的元素
print(a[a > 25])  # [30 40 50]

# 多个条件：每个条件都要加括号
print(a[(a > 15) & (a < 45)])  # [20 30 40]，且
print(a[(a < 20) | (a > 40)])  # [10 50]，或

# 2、二维数组
b = np.array([
    [11, 12, 13],
    [21, 22, 23],
    [31, 32, 33]
])

print(b[1, 2])      # 23：第 2 行、第 3 列的元素
print(b[1, :])      # [21 22 23]：第 2 行
print(b[:, 0])      # [11 21 31]：第 1 列
# 第一个参数控制行，第二个参数控制列。0:2，前两行。1:3，第2列，第三列。
# 前两行中，第 2～3 列，对应的值。
print(b[0:2, 1:3])
print(b[b > 20])    # [21 22 23 31 32 33]：满足条件的元素